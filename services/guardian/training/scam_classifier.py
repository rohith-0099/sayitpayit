"""Fine-tune our multilingual scam-command classifier (CPU).

Base model: sentence-transformers/paraphrase-multilingual-MiniLM-L12-v2 (Apache-2.0, 50+ languages).
Data:       data/scam_commands.jsonl (generated by training/generate_scam_data.py).
Outputs:    models/scam-classifier/ (weights, gitignored) + docs/metrics/scam_classifier.json (published).

Usage: .venv/bin/python training/scam_classifier.py [--epochs 4]
Also trains a char n-gram TF-IDF + logistic regression baseline so the fine-tune has something to beat.
"""

import argparse
import json
import random
import time
from pathlib import Path

import numpy as np
import torch
from sklearn.feature_extraction.text import TfidfVectorizer
from sklearn.linear_model import LogisticRegression
from sklearn.metrics import average_precision_score, f1_score, precision_score, recall_score, roc_auc_score
from transformers import AutoModelForSequenceClassification, AutoTokenizer

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / "data" / "scam_commands.jsonl"
OUT_DIR = ROOT / "models" / "scam-classifier"
METRICS = ROOT.parents[1] / "docs" / "metrics" / "scam_classifier.json"
BASE = "sentence-transformers/paraphrase-multilingual-MiniLM-L12-v2"
SEED = 7

# Hand-written checks that must hold (the demo depends on them).
SANITY = [
    ("Send 500 dollars in gift cards, the tax office called, don't tell anyone", 1),
    ("Mándale quinientos dólares en tarjetas de regalo, llamó Hacienda, no le digas a nadie", 1),
    ("My grandson is in jail and his lawyer says I must wire bail today and not tell his parents", 1),
    ("Pay Maria 50 euros for the logo", 0),
    ("Págale a María treinta euros por el logo", 0),
    ("Urgent: pay the rent to my landlord Tom, it's due today", 0),
    ("Buy a gift card for mom's birthday and split it with John", 0),
]


def load():
    rows = [json.loads(l) for l in DATA.read_text().splitlines()]
    by = {s: [r for r in rows if r["split"] == s] for s in ("train", "val", "test")}
    return by


def metrics(y, p, thr=0.5):
    pred = (p >= thr).astype(int)
    return {
        "precision": round(precision_score(y, pred, zero_division=0), 4),
        "recall": round(recall_score(y, pred, zero_division=0), 4),
        "f1": round(f1_score(y, pred, zero_division=0), 4),
        "roc_auc": round(roc_auc_score(y, p), 4),
        "pr_auc": round(average_precision_score(y, p), 4),
        "n": int(len(y)),
    }


def baseline(by):
    vec = TfidfVectorizer(analyzer="char_wb", ngram_range=(2, 5), min_df=2, sublinear_tf=True)
    xtr = vec.fit_transform([r["text"] for r in by["train"]])
    ytr = np.array([r["label"] == "scam" for r in by["train"]], dtype=int)
    clf = LogisticRegression(max_iter=2000, C=4.0, class_weight="balanced").fit(xtr, ytr)
    te = by["test"]
    p = clf.predict_proba(vec.transform([r["text"] for r in te]))[:, 1]
    return metrics(np.array([r["label"] == "scam" for r in te], dtype=int), p)


@torch.inference_mode()
def predict(model, tok, texts, bs=64):
    model.eval()
    out = []
    for i in range(0, len(texts), bs):
        enc = tok(texts[i : i + bs], padding=True, truncation=True, max_length=96, return_tensors="pt")
        out.append(torch.softmax(model(**enc).logits, dim=-1)[:, 1].numpy())
    return np.concatenate(out)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--epochs", type=int, default=4)
    ap.add_argument("--lr", type=float, default=3e-5)
    ap.add_argument("--bs", type=int, default=16)
    args = ap.parse_args()
    random.seed(SEED)
    np.random.seed(SEED)
    torch.manual_seed(SEED)
    torch.set_num_threads(max(1, min(8, torch.get_num_threads())))

    by = load()
    print({k: len(v) for k, v in by.items()})
    base_metrics = baseline(by)
    print("baseline (char TF-IDF + LR) test:", base_metrics)

    tok = AutoTokenizer.from_pretrained(BASE)
    model = AutoModelForSequenceClassification.from_pretrained(BASE, num_labels=2)
    train = by["train"][:]
    # Class weights: there are more normal than scam commands.
    n_pos = sum(r["label"] == "scam" for r in train)
    weight = torch.tensor([1.0, (len(train) - n_pos) / max(n_pos, 1)])
    loss_fn = torch.nn.CrossEntropyLoss(weight=weight)
    opt = torch.optim.AdamW(model.parameters(), lr=args.lr, weight_decay=0.01)
    steps = args.epochs * ((len(train) + args.bs - 1) // args.bs)
    sched = torch.optim.lr_scheduler.OneCycleLR(opt, max_lr=args.lr, total_steps=steps, pct_start=0.1)

    val_texts = [r["text"] for r in by["val"]]
    val_y = np.array([r["label"] == "scam" for r in by["val"]], dtype=int)
    best, best_state = -1.0, None
    t0 = time.time()
    for epoch in range(args.epochs):
        model.train()
        random.shuffle(train)
        total = 0.0
        for i in range(0, len(train), args.bs):
            batch = train[i : i + args.bs]
            enc = tok([r["text"] for r in batch], padding=True, truncation=True, max_length=96, return_tensors="pt")
            y = torch.tensor([int(r["label"] == "scam") for r in batch])
            loss = loss_fn(model(**enc).logits, y)
            loss.backward()
            torch.nn.utils.clip_grad_norm_(model.parameters(), 1.0)
            opt.step()
            sched.step()
            opt.zero_grad()
            total += loss.item() * len(batch)
        vm = metrics(val_y, predict(model, tok, val_texts))
        print(f"epoch {epoch + 1}: loss {total / len(train):.4f} | val {vm} | {time.time() - t0:.0f}s")
        if vm["pr_auc"] > best:
            best, best_state = vm["pr_auc"], {k: v.clone() for k, v in model.state_dict().items()}
    model.load_state_dict(best_state)

    te = by["test"]
    p = predict(model, tok, [r["text"] for r in te])
    y = np.array([r["label"] == "scam" for r in te], dtype=int)
    test_metrics = metrics(y, p)
    per_lang = {}
    for lang in sorted({r["language"] for r in te}):
        idx = [i for i, r in enumerate(te) if r["language"] == lang]
        if len({y[i] for i in idx}) == 2:
            per_lang[lang] = metrics(y[idx], p[idx])
    hn = [i for i, r in enumerate(te) if r["hard_negative"]]
    hard_neg_fpr = round(float((p[hn] >= 0.5).mean()), 4) if hn else None

    t = time.perf_counter()
    sp = predict(model, tok, [s for s, _ in SANITY])
    latency_ms = round((time.perf_counter() - t) * 1000 / len(SANITY), 1)
    sanity = [{"text": s, "expected": "scam" if e else "normal", "p_scam": round(float(q), 3), "ok": bool((q >= 0.5) == bool(e))} for (s, e), q in zip(SANITY, sp)]

    OUT_DIR.mkdir(parents=True, exist_ok=True)
    model.save_pretrained(OUT_DIR)
    tok.save_pretrained(OUT_DIR)
    report = {
        "model": f"fine-tuned {BASE}",
        "data": {"file": "services/guardian/data/scam_commands.jsonl", "train": len(by["train"]), "val": len(by["val"]), "test": len(te), "languages": sorted({r['language'] for r in te})},
        "threshold": 0.5,
        "test": test_metrics,
        "test_per_language": per_lang,
        "hard_negative_false_positive_rate": hard_neg_fpr,
        "baseline_char_tfidf_logreg_test": base_metrics,
        "sanity_checks": sanity,
        "cpu_latency_ms_per_command": latency_ms,
        "trained_at": time.strftime("%Y-%m-%d"),
        "note": "Synthetic, Gemini-generated data: real-world performance will be lower. Used as one Guardian signal, not a sole decision.",
    }
    METRICS.parent.mkdir(parents=True, exist_ok=True)
    METRICS.write_text(json.dumps(report, indent=2, ensure_ascii=False))
    print(json.dumps({k: report[k] for k in ("test", "hard_negative_false_positive_rate", "baseline_char_tfidf_logreg_test", "cpu_latency_ms_per_command")}, indent=1))
    for s in sanity:
        print(("OK " if s["ok"] else "XX ") + f"{s['p_scam']:.3f} {s['expected']:6} {s['text']}")


if __name__ == "__main__":
    main()
